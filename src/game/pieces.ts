export function pieceCells(type: PieceType, rotation: number): Cell[] {
  return SHAPES[type][((rotation % 4) + 4) % 4]!;
}

// A 7-bag randomizer: each of the 7 pieces appears exactly once per shuffled bag,
// so the player never sees long unlucky droughts of one piece.
export class PieceBag {
  private bag: PieceType[] = [];

  next(rng: () => number = Math.random): PieceType {
    if (this.bag.length === 0) {
      this.bag = [...PIECE_TYPES];
      for (let i = this.bag.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1));
        [this.bag[i], this.bag[j]] = [this.bag[j]!, this.bag[i]!];
      }
    }
    return this.bag.pop()!;
  }
}
